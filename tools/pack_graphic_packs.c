/* Packs Cemu's community graphic packs into a C source file the core is
 * built with (see LibretroGraphicPacks.cpp, which unpacks them).
 *
 *   pack_graphic_packs <cemu_graphic_packs dir> <out.c>
 *
 * The packs are laid out the way that repository's release zip is:
 * the folders inside Enhancements, Resolutions, Mods, Workarounds and
 * src side by side, with LICENSE.md. The archive is a run of entries,
 * each the path (UTF-8, '/'-separated, NUL-terminated), the size as
 * four bytes little-endian and the data, compressed whole with zlib.
 * Entries are sorted, so the same tree gives the same file.
 *
 * Runs on the build machine; built with zlib's deflate sources. */
#include <dirent.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>

#include "zlib.h"

struct entry
{
   char *path;  /* in the archive */
   char *file;  /* on disk */
};

static struct entry *entries;
static size_t entry_count, entry_cap;

static void add(const char *path, const char *file)
{
   if (entry_count == entry_cap)
   {
      entry_cap = entry_cap ? entry_cap * 2 : 1024;
      entries   = (struct entry*)realloc(entries, entry_cap * sizeof(*entries));
      if (!entries)
         exit(1);
   }
   entries[entry_count].path = strdup(path);
   entries[entry_count].file = strdup(file);
   entry_count++;
}

static int is_dir(const char *file)
{
   struct stat st;
   return stat(file, &st) == 0 && S_ISDIR(st.st_mode);
}

static void walk(const char *path, const char *file)
{
   DIR *d = opendir(file);
   struct dirent *de;
   if (!d)
      return;
   while ((de = readdir(d)))
   {
      char p[4096], f[4096];
      if (de->d_name[0] == '.')
         continue;
      snprintf(p, sizeof(p), "%s%s%s", path, *path ? "/" : "", de->d_name);
      snprintf(f, sizeof(f), "%s/%s", file, de->d_name);
      if (is_dir(f))
         walk(p, f);
      else
         add(p, f);
   }
   closedir(d);
}

static int by_path(const void *a, const void *b)
{
   return strcmp(((const struct entry*)a)->path, ((const struct entry*)b)->path);
}

static unsigned char *buf;
static size_t buf_len, buf_cap;

static void put(const void *data, size_t len)
{
   if (buf_len + len > buf_cap)
   {
      while (buf_len + len > buf_cap)
         buf_cap = buf_cap ? buf_cap * 2 : (1u << 20);
      buf = (unsigned char*)realloc(buf, buf_cap);
      if (!buf)
         exit(1);
   }
   memcpy(buf + buf_len, data, len);
   buf_len += len;
}

int main(int argc, char **argv)
{
   static const char *groups[] = { "Enhancements", "Resolutions", "Mods", "Workarounds", "src" };
   unsigned char *z;
   uLongf z_len;
   uint64_t hash = 1469598103934665603ull;
   FILE *out;
   size_t i;
   char file[4096];

   if (argc != 3)
      return 2;
   for (i = 0; i < sizeof(groups) / sizeof(groups[0]); i++)
   {
      snprintf(file, sizeof(file), "%s/%s", argv[1], groups[i]);
      walk("", file);
   }
   if (entry_count)
   {
      snprintf(file, sizeof(file), "%s/LICENSE.md", argv[1]);
      add("LICENSE.md", file);
   }
   qsort(entries, entry_count, sizeof(*entries), by_path);

   for (i = 0; i < entry_count; i++)
   {
      unsigned char size[4];
      long n;
      unsigned char *data;
      FILE *f = fopen(entries[i].file, "rb");
      if (!f)
         return 1;
      fseek(f, 0, SEEK_END);
      n = ftell(f);
      fseek(f, 0, SEEK_SET);
      data = (unsigned char*)malloc(n ? (size_t)n : 1);
      if (!data || fread(data, 1, (size_t)n, f) != (size_t)n)
         return 1;
      fclose(f);
      size[0] = (unsigned char)(n);
      size[1] = (unsigned char)(n >> 8);
      size[2] = (unsigned char)(n >> 16);
      size[3] = (unsigned char)(n >> 24);
      put(entries[i].path, strlen(entries[i].path) + 1);
      put(size, 4);
      put(data, (size_t)n);
      free(data);
   }
   for (i = 0; i < buf_len; i++)
      hash = (hash ^ buf[i]) * 1099511628211ull;

   z_len = compressBound((uLong)buf_len);
   z = (unsigned char*)malloc(z_len ? z_len : 1);
   if (!z || compress2(z, &z_len, buf, (uLong)buf_len, 9) != Z_OK)
      return 1;

   if (!(out = fopen(argv[2], "wb")))
      return 1;
   fprintf(out, "/* Generated by tools/pack_graphic_packs.c from dependencies/cemu_graphic_packs */\n"
         "#include <stddef.h>\n\n"
         "extern const size_t g_libretro_graphic_packs_size = %lu;\n"
         "extern const size_t g_libretro_graphic_packs_unpacked_size = %lu;\n"
         "extern const char g_libretro_graphic_packs_version[] = \"%016llx\";\n"
         "extern const unsigned char g_libretro_graphic_packs[] =\n\"",
         buf_len ? (unsigned long)z_len : 0ul, (unsigned long)buf_len, (unsigned long long)hash);
   /* octal escapes: a following digit never extends them past three */
   for (i = 0; buf_len && i < z_len; i++)
   {
      fprintf(out, "\\%03o", z[i]);
      if ((i & 31) == 31)
         fputs("\"\n\"", out);
   }
   fputs("\";\n", out);
   return fclose(out) == 0 ? 0 : 1;
}
